import { createHash } from 'node:crypto'
import {
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
export function publicFiles(directory) {
  return readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) => {
      const path = resolve(directory, entry.name)
      return entry.isDirectory()
        ? publicFiles(path)
        : path.endsWith('.md')
          ? [path]
          : []
    })
    .sort()
}
export function referenceOutputs() {
  const sourceRoot = resolve(root, 'docs/public')
  const version = JSON.parse(
    readFileSync(resolve(root, 'package.json'), 'utf8'),
  ).version
  const outputs = new Map()
  const files = publicFiles(sourceRoot).map((path) => {
    const source = readFileSync(path, 'utf8')
    const name = relative(sourceRoot, path).replaceAll('\\', '/')
    // Preserve template icons for the website; strip them from the compact AI reference below.
    const text = source
    const target = `public/reference/docs/${name}`
    outputs.set(target, text)
    return {
      path: `docs/${name}`,
      sha256: createHash('sha256').update(text).digest('hex'),
    }
  })
  const navigation = readFileSync(resolve(sourceRoot, 'docs.json'), 'utf8')
  JSON.parse(navigation)
  outputs.set('public/reference/docs.json', navigation)
  files.push({
    path: 'docs.json',
    sha256: createHash('sha256').update(navigation).digest('hex'),
  })
  const reference = outputs
    .get('public/reference/docs/reference.md')
    .replace(/^---\s*\n[\s\S]*?\n---\s*\n?/, '')
    .replace(/{%\s*lucide\s+[^%]*%}/g, '')
  outputs.set('public/reference.md', reference)
  outputs.set(
    'src/lib/configuration-reference.mjs',
    `// Generated by scripts/build-reference.mjs from docs/public/reference.md.\n// prettier-ignore\nexport const configurationReferenceVersion = ${JSON.stringify(version)}\n// prettier-ignore\nexport const configurationReference = ${JSON.stringify(reference)}\n`,
  )
  outputs.set(
    'src/lib/configuration-reference.d.mts',
    'export declare const configurationReferenceVersion: string\nexport declare const configurationReference: string\n',
  )
  outputs.set(
    'public/reference/manifest.json',
    JSON.stringify({ version, reference: '/reference.md', files }, null, 2) +
      '\n',
  )
  return outputs
}
export function buildReference({ check = false } = {}) {
  const outputs = referenceOutputs()
  if (!check)
    rmSync(resolve(root, 'public/reference'), { recursive: true, force: true })
  for (const [path, source] of outputs) {
    const target = resolve(root, path)
    if (check) {
      if (readFileSync(target, 'utf8') !== source)
        throw new Error(`Stale reference artifact: ${path}`)
    } else {
      mkdirSync(dirname(target), { recursive: true })
      writeFileSync(target, source)
    }
  }
}
if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  buildReference({ check: process.argv.includes('--check') })
}
